'''
Crie um dicionário:

notas = {
    "matematica": 8,
    "portugues": 7,
    "python": 9
}

Mostre separadamente:

todas as chaves usando .keys()
todos os valores usando .values()
todos os pares chave/valor usando .items()

'''


notas = {
    "matematica": 8,
    "portugues": 7,
    "python": 9
}

print(notas.keys())
print()
print(notas.values())
print()
print(notas.items())